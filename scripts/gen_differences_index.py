#!/usr/bin/env python3
"""Check the DIFFERENCES entries and write the one-page view of them.

Each entry is its own file, docs/agent/differences/NNNN.md (DIFFERENCES 51 is 0051.md), and starts
`N. <a id="d-N"></a>**Lead sentence.** ...`. One file per entry means two branches that add
different entries never touch the same lines, so they never conflict.

    python3 scripts/gen_differences_index.py          # check, then write docs/agent/DIFFERENCES.generated.md
    python3 scripts/gen_differences_index.py --check  # check only (CI); exit 1 on any error
    python3 scripts/gen_differences_index.py --import OLD.md [--base BASE.md]
        # write the entries of a one-file DIFFERENCES.md (the old layout) as entry files; with
        # --base, only the entries that differ from BASE (so a branch's own additions and edits)

The generated page is not committed; it holds the index (number and lead sentence) and every entry.
Checked: the file name, the entry number and the anchor id agree; each file holds exactly one entry;
no conflict markers.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIR = ROOT / "docs/agent/differences"
OUT = ROOT / "docs/agent/DIFFERENCES.generated.md"
ENTRY = re.compile(r'^(\d+)\. <a id="d-(\d+)"></a>\*\*(.*?)\*\*', re.M)
START = re.compile(r'^\d+\. <a id="d-\d+"></a>', re.M)
ANCHOR = re.compile(r'<a id="d-')
MARKER = re.compile(r"^(<<<<<<<|=======|>>>>>>>)", re.M)
NAME = re.compile(r"^(\d{4})\.md$")
TITLE = "# Intentional Differences (generated view)"


def file_name(number):
    return f"{int(number):04d}.md"


def split_entries(text):
    """The entries of a one-file DIFFERENCES.md (old layout): {number: entry text}."""
    marker = "\n## Entries\n"
    at = text.find(marker)
    body = text[at + len(marker):] if at >= 0 else text
    starts = [m.start() for m in START.finditer(body)]
    out = {}
    for i, start in enumerate(starts):
        end = starts[i + 1] if i + 1 < len(starts) else len(body)
        chunk = body[start:end].strip("\n")
        match = ENTRY.match(chunk)
        if match:
            out[int(match.group(1))] = chunk + "\n"
    return out


def read_entries(directory=DIR):
    """Return ({number: (lead, text)}, errors)."""
    errors, entries = [], {}
    if not directory.is_dir():
        return {}, [f"{directory} is missing"]
    for path in sorted(directory.iterdir()):
        if path.name == "README.md":
            continue
        match = NAME.match(path.name)
        if not match:
            errors.append(f"{path.name}: entry files are named NNNN.md")
            continue
        text = path.read_text()
        if MARKER.search(text):
            errors.append(f"{path.name}: merge conflict markers")
            continue
        found = ENTRY.findall(text)
        if len(found) != 1 or len(ANCHOR.findall(text)) != 1 or not ENTRY.match(text):
            errors.append(f"{path.name}: holds exactly one entry, starting 'N. <a id=\"d-N\"></a>**lead**'")
            continue
        number, ident, lead = found[0]
        if number != ident:
            errors.append(f"{path.name}: entry {number} has id d-{ident}")
        if int(number) != int(match.group(1)):
            errors.append(f"{path.name}: holds entry {number}")
        if int(number) in entries:
            errors.append(f"duplicate entry {number}")
        entries[int(number)] = (lead, text.strip("\n") + "\n")
    return entries, errors


def render(entries):
    rows = "\n".join(f"| [{n}](#d-{n}) | {entries[n][0].replace('|', chr(92) + '|')} |" for n in sorted(entries))
    body = "\n".join(entries[n][1] for n in sorted(entries))
    return (
        f"{TITLE}\n\nGenerated by `python3 scripts/gen_differences_index.py` from docs/agent/differences/; "
        "do not edit or commit.\n\n## Index\n\n| # | Difference |\n|---|---|\n"
        f"{rows}\n\n## Entries\n\n{body}"
    )


def import_old(old_path, base_path=None, directory=DIR):
    """Write the entries of OLD as entry files; with BASE, only those that differ from BASE."""
    old = split_entries(pathlib.Path(old_path).read_text())
    base = split_entries(pathlib.Path(base_path).read_text()) if base_path else {}
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    for number, text in sorted(old.items()):
        if base.get(number) == text:
            continue
        target = directory / file_name(number)
        if not target.exists() or target.read_text() != text:
            target.write_text(text)
            written.append(number)
    return written


def main(argv):
    if not DIR.is_dir():
        print("differences index skipped: internal notes are not in this tree")
        return 0
    if "--import" in argv:
        old = argv[argv.index("--import") + 1]
        base = argv[argv.index("--base") + 1] if "--base" in argv else None
        written = import_old(old, base)
        print(f"gen_differences_index: wrote {len(written)} entries {written}")
    entries, errors = read_entries()
    for err in errors:
        print(f"gen_differences_index: {err}", file=sys.stderr)
    if errors:
        return 1
    if "--check" not in argv:
        OUT.write_text(render(entries))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
